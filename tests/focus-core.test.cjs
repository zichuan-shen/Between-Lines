const assert=require('node:assert/strict');
const C=require('../assets/focus-core.js');
let now=1000000,s=C.start({id:'one',minutes:25,title:'做完第一版',taskId:'task'},now);
assert.equal(C.remaining(s,now+60000),24*60000);
s=C.pause(s,now+120000);assert.equal(s.remainingMs,23*60000);
assert.equal(C.remaining(s,now+3600000),23*60000,'Paused time is excluded');
s=C.resume(s,now+3600000);assert.equal(s.endAt,now+3600000+23*60000);
const reopened=C.restore(JSON.parse(JSON.stringify({session:s,history:[]})));
assert.equal(C.remaining(reopened.session,now+3600000+60000),22*60000,'Reload uses the stored deadline');
const expectedEnd=s.endAt;s=C.settle(s,expectedEnd+7200000);
assert.equal(s.status,'review');assert.equal(s.endedAt,expectedEnd,'Sleep does not add extra focus minutes');
assert.equal(C.record(s,'完成').elapsedMs,25*60000);
assert.equal(C.settle(s,expectedEnd+8000000),s,'Completion is idempotent');
s=C.start({id:'two',minutes:45,title:'提前结束'},now);s=C.finish(s,now+95000);
assert.equal(C.record(s,'下次继续').elapsedMs,95000);assert.equal(s.completed,false);
s=C.start({id:'three',minutes:1,title:'刚好到点'},now);s=C.pause(s,now+60000);assert.equal(s.status,'review');
assert.throws(()=>C.start({id:'x',minutes:0,title:'x'},now));assert.throws(()=>C.start({id:'x',minutes:181,title:'x'},now));assert.throws(()=>C.start({id:'x',minutes:1.5,title:'x'},now));assert.throws(()=>C.start({id:'x',minutes:25,title:' '},now));
assert.equal(C.restore({session:{status:'running',endAt:'bad'}}).session,null);
const record={id:'r',title:'x',elapsedMs:100,endedAt:now};assert.equal(C.restore({history:[record,record,null]}).history.length,1);
console.log('PASS: absolute countdown, pause/resume, reload, sleep recovery, exact completion, early stop accounting, validation, corrupted state, record deduplication.');
